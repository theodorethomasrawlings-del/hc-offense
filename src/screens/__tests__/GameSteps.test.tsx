import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { createMemoryRouter, RouterProvider } from 'react-router-dom'
import { routes } from '../../App'
import { db } from '../../db/db'
import { useGameStore } from '../../store/gameStore'

beforeEach(() => {
  Object.defineProperty(window, 'innerWidth', { configurable: true, value: 390 })
})

async function liveGame() {
  await db.games.clear()
  await db.possessions.clear()
  useGameStore.setState({ game: null, possessions: [], tagged: [], draft: {}, loaded: false })
  await useGameStore.getState().startGame({ opponent: 'Siena', date: '2026-11-02', home: true })
  const router = createMemoryRouter(routes, { initialEntries: ['/game'] })
  render(<RouterProvider router={router} />)
  await screen.findByText('#1')
  return router
}
const btn = (name: RegExp) => screen.getByRole('button', { name })
const click = (name: RegExp) => fireEvent.click(btn(name))
const q = (text: string) => expect(screen.getByRole('heading', { level: 1 })).toHaveTextContent(text)

test('play → action → shot → made → save: five taps, three points, paint touch counted', async () => {
  await liveGame()
  q('What play?')
  click(/^Tiger$/)
  q('Tiger: which action?')
  click(/^Ice$/)
  q('How did it end?')
  click(/^paint touch 3$/i)
  q('made?')
  click(/^made$/i)
  q('Save, or add details')
  expect(screen.getByLabelText('points this possession')).toHaveTextContent('3 PTS')
  click(/^save →$/i)
  await screen.findByText('#2')
  expect(useGameStore.getState().possessions[0]).toMatchObject({ points: 3, family: 'Tiger', action: 'Ice', shot: 'PAINT3', paintTouches: 1 })
  expect(screen.getByLabelText('game totals')).toHaveTextContent('PPP 3.00')
  q('What play?')
})

test('a turnover skips straight to details', async () => {
  await liveGame()
  click(/^Other$/)
  click(/^Freelance$/)
  click(/turnover/i)
  q('Save, or add details')
  click(/^save →$/i)
  await screen.findByText('#2')
  expect(useGameStore.getState().possessions[0]).toMatchObject({ points: 0, result: 'TO' })
})

test('a miss asks about the rebound; OREB opens a fresh page under the same number', async () => {
  await liveGame()
  click(/^Tiger$/)
  click(/^Blade$/)
  click(/mid-range 2/i)
  click(/^missed$/i)
  q('Who got the rebound?')
  click(/OREB, keep going/i)
  q('What play?')
  expect(screen.getByRole('status', { name: 'so far' })).toHaveTextContent('#1 shot 2')
  click(/^Spider$/)
  click(/^X$/)
  click(/rim \/ deep paint 2/i)
  click(/and-1/i)
  q('Free throws made?')
  click(/^1\/1$/)
  q('Save, or add details')
  click(/^save →$/i)
  await screen.findByText('#2')
  const p = useGameStore.getState().possessions[0]
  expect(p).toMatchObject({ n: 1, points: 3, orebs: 1, family: 'Spider', action: 'X', ftm: 1, fta: 1 })
  expect(p.chunks).toHaveLength(2)
})

test('a missed last free throw asks about the rebound', async () => {
  await liveGame()
  click(/^5$/)
  click(/^Penny$/)
  click(/fouled, no shot/i)
  click(/^1\/2$/)
  q('Who got the rebound?')
  click(/they got it/i)
  click(/^save →$/i)
  await screen.findByText('#2')
  expect(useGameStore.getState().possessions[0]).toMatchObject({ points: 1, result: 'FOUL', ftm: 1, fta: 2 })
})

test('back retraces a step; edit last opens details and recomputes points', async () => {
  await liveGame()
  click(/^Point$/)
  click(/^Roger$/)
  click(/rim \/ deep paint 2/i)
  click(/← back/i)
  q('How did it end?')
  click(/rim \/ deep paint 2/i)
  click(/^made$/i)
  click(/^save →$/i)
  await screen.findByText('#2')
  click(/edit last/i)
  await screen.findByText('Editing #1')
  q('Save, or add details')
  click(/change shot/i)
  click(/mid-range 2/i)
  click(/^missed$/i)
  click(/they got it/i)
  click(/^save$/i)
  await screen.findByText('#2')
  expect(useGameStore.getState().possessions[0]).toMatchObject({ points: 0, shot: 'MID2' })
})

test('media timeout goes to the summary', async () => {
  const router = await liveGame()
  click(/^Transition$/)
  click(/^Layup$/)
  click(/turnover/i)
  click(/^save →$/i)
  await screen.findByText('#2')
  click(/^media to$/i)
  await waitFor(() => expect(router.state.location.pathname).toBe('/summary'))
  expect(useGameStore.getState().game?.timeouts).toEqual([1])
})
